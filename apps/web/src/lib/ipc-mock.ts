function versionOf(path: string): number {
  const version = VERSIONS.get(path)
  if (version === undefined) throw new Error(`文件不存在：${path}`)
  return version
}

/**
 * 写盘守卫：与 `hbot-workspace` 的规则对齐（docs/06-ide.md §4.2）。
 * 契约是"拒绝"而不是"静默失败"。
 */
/** 归一化项目内路径；越界（绝对路径、盘符、`..`）直接拒绝，读与写共用。 */
function assertInsideProject(path: string): string {
  const normalized = path.replace(/\\/g, '/')
  const segments = normalized.split('/')
  const absolute = normalized.startsWith('/') || /^[A-Za-z]:/.test(normalized)
  if (normalized.length === 0 || absolute || segments.includes('..')) {
    throw new Error(`拒绝：路径必须位于项目内（${path}）`)
  }
  return normalized
}

function assertWritable(path: string): void {
  const normalized = assertInsideProject(path)
  const segments = normalized.split('/')
  if (segments[0] === '.hbot') {
    throw new Error(`拒绝写入：${path} 属于运行数据（.hbot/）`)
  }
  if (normalized === 'hbot.d.ts') {
    throw new Error('拒绝写入：hbot.d.ts 由核心生成，请改 Rust 侧 dts.rs')
  }
}

function logLine(level: LogLevel, source: string, message: string, at: number): LogLine {
  return { level, source, message, at }
}

function transition(status: BotStatus, queueDepth: number, lines: LogLine[]): BotTransition {
  return { bot: { botId: BOT_ID, status, queueDepth }, lines }
}

function searchFiles(query: string, caseSensitive: boolean): SearchResult {
  const needle = caseSensitive ? query : query.toLowerCase()
  const hits: SearchHit[] = []
  let truncated = false

  for (const [path, content] of FILES) {
    const lines = content.split('\n')
    for (let index = 0; index < lines.length; index += 1) {
      const line = lines[index] ?? ''
      const haystack = caseSensitive ? line : line.toLowerCase()
      const columnIndex = haystack.indexOf(needle)
      if (columnIndex === -1) continue
      if (hits.length >= MAX_SEARCH_HITS) {
        truncated = true
        break
      }
      hits.push({
        path,
        line: index + 1,
        column: columnIndex + 1,
        preview: line.trim().slice(0, PREVIEW_MAX),
      })
    }
    if (truncated) break
  }

  return { query, hits, truncated }
}

/** mock 分发：与 `dispatch()` 的返回类型一致，由 ipc.ts 收窄。 */
export async function mockDispatch(command: Command): Promise<CommandOutputs[CommandType]> {
  switch (command.type) {
    case 'workspace.tree':
      return structuredClone(TREE)

    case 'fs.read': {
      const path = assertInsideProject(command.path)
      const content = FILES.get(path)
      if (content === undefined) throw new Error(`文件不存在：${command.path}`)
      return { path, content, version: versionOf(path) }
    }

    case 'fs.write': {
      assertWritable(command.path)
      const path = command.path.replace(/\\/g, '/')
      FILES.set(path, command.content)
      const version = versionOf(path) + 1
      VERSIONS.set(path, version)
      return { path, version }
    }

    case 'search':
      return searchFiles(command.query, command.caseSensitive ?? false)

    case 'bot.start': {
      const now = Date.now()
      return transition('running', 0, [
        logLine('info', 'supervisor', `bot ${command.botId} 启动（mock）`, now),
        logLine('info', 'supervisor', '平台适配器：onebot11（mock，未连接网络）', now),
        logLine('debug', 'session', '会话队列就绪，容量 64', now),
      ])
    }

    case 'bot.stop': {
      const now = Date.now()
      return transition('stopped', 0, [
        logLine('info', 'supervisor', `bot ${command.botId} 已停止（mock）`, now),
      ])
    }

    case 'bot.status':
      return { botId: command.botId, status: 'stopped', queueDepth: 0 }

    case 'agent.send':
      return {
        messageId: `mock-${Date.now()}`,
        reply: `（mock 回声）收到：「${command.text}」。真实 Agent 循环在 Rust 侧（crates/hbot-agent），M1 接入后替换这里。`,
      }

    default: {
      const exhaustive: never = command
      throw new Error(`未实现的命令：${JSON.stringify(exhaustive)}`)
    }
  }
}