//! TypeScript 契约生成：把 UI 可见的类型写成「一类型一文件」。
//!
//! 生成物落在 `apps/web/src/generated/`，由 `cargo xtask gen` 调用，**不要手改**。
//!
//! # 为什么不用 `#[ts(export)]`
//!
//! ts-rs 的 `#[ts(export)]` 会额外生成一个隐藏的 `#[test]`；跑 `cargo test` 就会顺手写文件，
//! 于是"本地绿、CI 红"取决于有没有跑过测试（AGENTS.md §7.16 记的就是这类坑）。
//! 这里改成显式枚举根类型 + 纯函数渲染（`ts/render.rs`）：同一份代码跑两次必然字节相同。
//!
//! # 形状约定
//!
//! - 一类型一文件：`Command.ts` 导出 `type Command`，UI 侧 `import type { Command } from
//!   "../generated/Command"`；
//! - `index.ts` 由本模块生成，只做转发（`export type { X } from "./X";`）；
//! - ID 新类型生成 `type ProjectId = string;`（`uuid-impl`），UI 拿到的是 `string`；
//! - 任意 JSON 字段（`Value`）生成 `unknown`，不是 `any`；
//! - `i64` 生成 `number`（线上是 JSON 数字，`bigint` 会让 `JSON.parse` 的结果无法直接赋值）。

mod render;

use std::collections::BTreeSet;
use std::fmt;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

pub use render::generated_files;

/// 生成文件的首行。手改的内容会在下次 `xtask gen` 被覆盖，`gen --check` 会红。
pub const HEADER: &str = "// @generated by xtask; do not edit";

/// 索引文件名（由生成逻辑写出，不手写）。
pub const INDEX_FILE: &str = "index.ts";

/// 一个生成文件：相对路径 + 完整内容。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    /// 相对生成目录的路径，正斜杠（如 `Command.ts`）。
    pub path: String,
    /// 文件全文（含头注释）。
    pub content: String,
}

/// 生成失败的原因。
///
/// 不用 `anyhow`：这个 crate 的公开 API 不暴露 `anyhow::Error`（AGENTS.md §5）。
#[derive(Debug)]
pub enum TsGenError {
    /// 读写生成目录失败。
    Io {
        /// 出错的路径。
        path: PathBuf,
        /// 底层错误。
        source: io::Error,
    },
    /// 类型没有 `output_path()`，无法确定文件名。
    NotExportable {
        /// Rust 类型名。
        name: String,
    },
    /// 根类型的依赖没有被导出（会生成悬空 import）。
    Missing {
        /// 依赖的 TS 类型名。
        type_name: String,
        /// 依赖期望的文件。
        file: String,
        /// 谁引用了它。
        referenced_by: String,
    },
    /// 目录里已有生成头文件，但本次没有生成它（陈旧类型）。
    Stale {
        /// 多余的文件名。
        file: String,
    },
    /// `gen --check`：磁盘内容与生成结果不一致。
    OutOfDate {
        /// 逐条问题（缺文件 / 多文件 / 内容不同）。
        problems: Vec<String>,
    },
}

impl fmt::Display for TsGenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Io { path, source } => write!(f, "无法写入 {}: {source}", path.display()),
            Self::NotExportable { name } => {
                write!(f, "类型 {name} 没有 output_path()，无法生成 TS 文件")
            }
            Self::Missing {
                type_name,
                file,
                referenced_by,
            } => write!(
                f,
                "{referenced_by} 依赖 {type_name}（期望文件 {file}），但根类型清单里没有它；\
                 请把它加进 crates/hbot-rpc/src/ts/render.rs 的根清单"
            ),
            Self::Stale { file } => write!(
                f,
                "生成目录里有陈旧文件 {file}；跑 `cargo xtask gen` 会删掉它"
            ),
            Self::OutOfDate { problems } => write!(
                f,
                "生成的 TS 与磁盘不一致（{} 处），请跑 `cargo xtask gen`：\n  {}",
                problems.len(),
                problems.join("\n  ")
            ),
        }
    }
}

impl std::error::Error for TsGenError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Io { source, .. } => Some(source),
            _ => None,
        }
    }
}

/// 把生成结果写进 `dir`，返回写出的文件数。
///
/// 已存在的旧文件被覆盖；带 [`HEADER`] 头但本次不再生成的文件会被删除（防陈旧类型）。
pub fn export_typescript(dir: &Path) -> Result<usize, TsGenError> {
    let files = generated_files()?;
    fs::create_dir_all(dir).map_err(|source| TsGenError::Io {
        path: dir.to_path_buf(),
        source,
    })?;

    let expected: BTreeSet<String> = files.iter().map(|f| f.path.clone()).collect();

    for file in &files {
        let path = dir.join(Path::new(&file.path));
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|source| TsGenError::Io {
                path: parent.to_path_buf(),
                source,
            })?;
        }
        fs::write(&path, &file.content).map_err(|source| TsGenError::Io {
            path: path.clone(),
            source,
        })?;
    }

    for name in stale_headers(dir, &expected)? {
        let path = dir.join(&name);
        fs::remove_file(&path).map_err(|source| TsGenError::Io { path, source })?;
    }

    Ok(files.len())
}

/// 校验 `dir` 与生成结果逐字节一致，返回文件数；不一致时返回 [`TsGenError::OutOfDate`]。
///
/// 供 CI 用：代码改了但没跑 `xtask gen` 就必须红。
pub fn check_typescript(dir: &Path) -> Result<usize, TsGenError> {
    let files = generated_files()?;
    let expected: BTreeSet<String> = files.iter().map(|f| f.path.clone()).collect();
    let mut problems = Vec::new();

    for file in &files {
        let path = dir.join(Path::new(&file.path));
        match fs::read_to_string(&path) {
            Ok(actual) if actual == file.content => {}
            Ok(_) => problems.push(format!("{} 内容不一致", file.path)),
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                problems.push(format!("缺少 {}", file.path));
            }
            Err(error) => {
                return Err(TsGenError::Io {
                    path: path.clone(),
                    source: error,
                });
            }
        }
    }

    for stale in stale_headers(dir, &expected)? {
        problems.push(format!("多余 {stale}（本次不再生成）"));
    }

    if problems.is_empty() {
        Ok(files.len())
    } else {
        Err(TsGenError::OutOfDate { problems })
    }
}

/// 扫描生成目录里带生成头的文件（非递归）。
fn stale_headers(dir: &Path, expected: &BTreeSet<String>) -> Result<Vec<String>, TsGenError> {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(source) => {
            return Err(TsGenError::Io {
                path: dir.to_path_buf(),
                source,
            });
        }
    };

    let mut stale = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|source| TsGenError::Io {
            path: dir.to_path_buf(),
            source,
        })?;
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) != Some("ts") {
            continue;
        }
        let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        if expected.contains(name) {
            continue;
        }
        let content = fs::read_to_string(&path).map_err(|source| TsGenError::Io {
            path: path.clone(),
            source,
        })?;
        if content.starts_with(HEADER) {
            stale.push(name.to_owned());
        }
    }
    Ok(stale)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_dir(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("hbot-tsgen-{tag}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        dir
    }

    #[test]
    fn generation_is_deterministic() {
        let first = generated_files().expect("first");
        let second = generated_files().expect("second");
        assert_eq!(first, second, "同一份代码两次生成必须逐字节相同");
    }

    #[test]
    fn every_file_starts_with_generated_header() {
        for file in generated_files().expect("gen") {
            assert!(file.content.starts_with(HEADER), "{} 缺少生成头", file.path);
        }
    }

    #[test]
    fn ids_are_plain_strings_for_the_ui() {
        let files = generated_files().expect("gen");
        let project = files
            .iter()
            .find(|f| f.path == "ProjectId.ts")
            .expect("ProjectId.ts");
        assert!(
            project.content.contains("type ProjectId = string;"),
            "ID 必须生成 string 别名，实际：{}",
            project.content
        );
    }

    #[test]
    fn export_then_check_round_trips() {
        let dir = temp_dir("roundtrip");
        let count = export_typescript(&dir).expect("export");
        assert!(count > 20, "根类型清单太小：{count}");
        assert_eq!(check_typescript(&dir).expect("check"), count);

        // 改一个字节 → check 必须红。
        let target = dir.join("Command.ts");
        let mut content = fs::read_to_string(&target).expect("read");
        content.push_str("// drifted\n");
        fs::write(&target, content).expect("write");
        assert!(check_typescript(&dir).is_err(), "内容漂移时必须报错");

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn stale_generated_files_are_removed_but_handwritten_ones_survive() {
        let dir = temp_dir("stale");
        export_typescript(&dir).expect("export");

        let stale = dir.join("OldThing.ts");
        fs::write(
            &stale,
            format!("{HEADER}\nexport type OldThing = string;\n"),
        )
        .expect("write");
        let handwritten = dir.join("hand-written.ts");
        fs::write(&handwritten, "export const keep = 1;\n").expect("write");

        export_typescript(&dir).expect("re-export");
        assert!(!stale.exists(), "带生成头的陈旧文件必须删除");
        assert!(handwritten.exists(), "手写文件不能被删");

        let _ = fs::remove_dir_all(&dir);
    }
}
